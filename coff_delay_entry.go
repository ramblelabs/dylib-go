package dylib

import "fmt"

// coffLazyEntry adapts an opaque native C resolver to an untyped native call.
// Its fast leaf range precedes the separately registered nonleaf slow range.
// Independent assembler references live in testdata/cofflazy.
type coffLazyEntry struct {
	code, unwind []byte
	slow         uint32
}

func makeCOFFLazyEntry(arch string, cell, context, helper uintptr) (coffLazyEntry, error) {
	if cell == 0 || context == 0 || helper == 0 {
		return coffLazyEntry{}, fmt.Errorf("lazy import entry requires native cell, context and resolver addresses")
	}
	width := uintptr(8)
	if arch == "386" {
		width = 4
	}
	if cell&(width-1) != 0 || context&(width-1) != 0 || arch == "arm64" && helper&3 != 0 {
		return coffLazyEntry{}, fmt.Errorf("misaligned native lazy import cell, context or resolver")
	}
	var out coffLazyEntry
	switch arch {
	case "amd64":
		// Preserve Windows integer/floating arguments and RAX/AL. The slow
		// path stores the resolver result in caller-provided shadow space,
		// then tail-jumps through that home slot without requiring caching.
		// Use REX.W+B on both memory-indirect tail jumps: the Windows
		// epilogue scanner requires W even though the CPU does not.
		out.code = []byte{
			0x49, 0xbb, 0x89, 0x67, 0x45, 0x23, 0x00, 0x00, 0x00, 0x00, 0x49, 0x83,
			0x3b, 0x00, 0x74, 0x03, 0x49, 0xff, 0x23, 0x55, 0x48, 0x81, 0xec, 0xe0,
			0x00, 0x00, 0x00, 0x48, 0x8d, 0xac, 0x24, 0xe0, 0x00, 0x00, 0x00, 0x48,
			0x89, 0x44, 0x24, 0x20, 0x48, 0x89, 0x4c, 0x24, 0x28, 0x48, 0x89, 0x54,
			0x24, 0x30, 0x4c, 0x89, 0x44, 0x24, 0x38, 0x4c, 0x89, 0x4c, 0x24, 0x40,
			0x48, 0x89, 0x7c, 0x24, 0x48, 0x48, 0x89, 0x74, 0x24, 0x50, 0xf3, 0x0f,
			0x7f, 0x44, 0x24, 0x60, 0xf3, 0x0f, 0x7f, 0x4c, 0x24, 0x70, 0xf3, 0x0f,
			0x7f, 0x94, 0x24, 0x80, 0x00, 0x00, 0x00, 0xf3, 0x0f, 0x7f, 0x9c, 0x24,
			0x90, 0x00, 0x00, 0x00, 0xf3, 0x0f, 0x7f, 0xa4, 0x24, 0xa0, 0x00, 0x00,
			0x00, 0xf3, 0x0f, 0x7f, 0xac, 0x24, 0xb0, 0x00, 0x00, 0x00, 0xf3, 0x0f,
			0x7f, 0xb4, 0x24, 0xc0, 0x00, 0x00, 0x00, 0xf3, 0x0f, 0x7f, 0xbc, 0x24,
			0xd0, 0x00, 0x00, 0x00, 0x48, 0xb9, 0x9a, 0x78, 0x56, 0x34, 0x00, 0x00,
			0x00, 0x00, 0x48, 0xb8, 0xab, 0x89, 0x67, 0x45, 0x00, 0x00, 0x00, 0x00,
			0xff, 0xd0, 0x48, 0x89, 0x45, 0x10, 0xf3, 0x0f, 0x6f, 0x44, 0x24, 0x60,
			0xf3, 0x0f, 0x6f, 0x4c, 0x24, 0x70, 0xf3, 0x0f, 0x6f, 0x94, 0x24, 0x80,
			0x00, 0x00, 0x00, 0xf3, 0x0f, 0x6f, 0x9c, 0x24, 0x90, 0x00, 0x00, 0x00,
			0xf3, 0x0f, 0x6f, 0xa4, 0x24, 0xa0, 0x00, 0x00, 0x00, 0xf3, 0x0f, 0x6f,
			0xac, 0x24, 0xb0, 0x00, 0x00, 0x00, 0xf3, 0x0f, 0x6f, 0xb4, 0x24, 0xc0,
			0x00, 0x00, 0x00, 0xf3, 0x0f, 0x6f, 0xbc, 0x24, 0xd0, 0x00, 0x00, 0x00,
			0x48, 0x8b, 0x44, 0x24, 0x20, 0x48, 0x8b, 0x4c, 0x24, 0x28, 0x48, 0x8b,
			0x54, 0x24, 0x30, 0x4c, 0x8b, 0x44, 0x24, 0x38, 0x4c, 0x8b, 0x4c, 0x24,
			0x40, 0x48, 0x8b, 0x7c, 0x24, 0x48, 0x48, 0x8b, 0x74, 0x24, 0x50, 0x4c,
			0x8d, 0x5d, 0x10, 0x48, 0x81, 0xc4, 0xe0, 0x00, 0x00, 0x00, 0x5d, 0x49,
			0xff, 0x23,
		}
		out.slow = 19
		out.unwind = []byte{
			0x01, 0x10, 0x04, 0xe5, 0x10, 0x03, 0x08, 0x01, 0x1c, 0x00, 0x01, 0x50,
		}
		le.PutUint64(out.code[2:], uint64(cell))
		le.PutUint64(out.code[138:], uint64(context))
		le.PutUint64(out.code[148:], uint64(helper))
	case "arm64":
		// Preserve original integer/floating argument registers and the incoming stack.
		out.code = []byte{
			0x30, 0xf1, 0x8c, 0xd2, 0xb0, 0x68, 0xa4, 0xf2, 0x10, 0x00, 0xc0, 0xf2,
			0x10, 0x00, 0xe0, 0xf2, 0x11, 0xfe, 0xdf, 0xc8, 0x51, 0x00, 0x00, 0xb4,
			0x20, 0x02, 0x1f, 0xd6, 0xff, 0x83, 0x03, 0xd1, 0xfd, 0x7b, 0x05, 0xa9,
			0xfd, 0x43, 0x01, 0x91, 0xe0, 0x07, 0x00, 0xa9, 0xe2, 0x0f, 0x01, 0xa9,
			0xe4, 0x17, 0x02, 0xa9, 0xe6, 0x1f, 0x03, 0xa9, 0xe8, 0x23, 0x00, 0xf9,
			0xe0, 0x07, 0x03, 0xad, 0xe2, 0x0f, 0x04, 0xad, 0xe4, 0x17, 0x05, 0xad,
			0xe6, 0x1f, 0x06, 0xad, 0x40, 0x13, 0x8f, 0xd2, 0xc0, 0x8a, 0xa6, 0xf2,
			0x00, 0x00, 0xc0, 0xf2, 0x00, 0x00, 0xe0, 0xf2, 0x70, 0x35, 0x91, 0xd2,
			0xf0, 0xac, 0xa8, 0xf2, 0x10, 0x00, 0xc0, 0xf2, 0x10, 0x00, 0xe0, 0xf2,
			0x00, 0x02, 0x3f, 0xd6, 0xf1, 0x03, 0x00, 0xaa, 0xe0, 0x07, 0x43, 0xad,
			0xe2, 0x0f, 0x44, 0xad, 0xe4, 0x17, 0x45, 0xad, 0xe6, 0x1f, 0x46, 0xad,
			0xe0, 0x07, 0x40, 0xa9, 0xe2, 0x0f, 0x41, 0xa9, 0xe4, 0x17, 0x42, 0xa9,
			0xe6, 0x1f, 0x43, 0xa9, 0xe8, 0x23, 0x40, 0xf9, 0xfd, 0x7b, 0x45, 0xa9,
			0xff, 0x83, 0x03, 0x91, 0x20, 0x02, 0x1f, 0xd6,
		}
		out.slow = 28
		out.unwind = []byte{
			0x22, 0x00, 0xa0, 0x10, 0xe2, 0x0a, 0x4a, 0x0e, 0xe4, 0xe3, 0xe3, 0xe3,
		}
		for half := uint32(0); half < 4; half++ {
			opcode := uint32(0xd2800000)
			if half != 0 {
				opcode = 0xf2800000
			}
			le.PutUint32(out.code[0:][half*4:], opcode|half<<21|uint32(uint64(cell)>>(half*16)&0xffff)<<5|16)
		}
		for half := uint32(0); half < 4; half++ {
			opcode := uint32(0xd2800000)
			if half != 0 {
				opcode = 0xf2800000
			}
			le.PutUint32(out.code[76:][half*4:], opcode|half<<21|uint32(uint64(context)>>(half*16)&0xffff)<<5|0)
		}
		for half := uint32(0); half < 4; half++ {
			opcode := uint32(0xd2800000)
			if half != 0 {
				opcode = 0xf2800000
			}
			le.PutUint32(out.code[92:][half*4:], opcode|half<<21|uint32(uint64(helper)>>(half*16)&0xffff)<<5|16)
		}
	case "386":
		if uint64(cell) > 0xffffffff || uint64(context) > 0xffffffff || uint64(helper) > 0xffffffff {
			return coffLazyEntry{}, fmt.Errorf("i386 lazy import address exceeds 32 bits")
		}
		// ECX/EDX and XMM arguments survive; volatile EAX carries the selected
		// target for the qualified cdecl/stdcall/fastcall/thiscall/vectorcall ABIs.
		out.code = []byte{
			0x83, 0x3d, 0x89, 0x67, 0x45, 0x23, 0x00, 0x74, 0x06, 0xff, 0x25, 0x89,
			0x67, 0x45, 0x23, 0x55, 0x89, 0xe5, 0x83, 0xe4, 0xf0, 0x81, 0xec, 0xa0,
			0x00, 0x00, 0x00, 0x89, 0x44, 0x24, 0x04, 0x89, 0x4c, 0x24, 0x08, 0x89,
			0x54, 0x24, 0x0c, 0xf3, 0x0f, 0x7f, 0x44, 0x24, 0x10, 0xf3, 0x0f, 0x7f,
			0x4c, 0x24, 0x20, 0xf3, 0x0f, 0x7f, 0x54, 0x24, 0x30, 0xf3, 0x0f, 0x7f,
			0x5c, 0x24, 0x40, 0xf3, 0x0f, 0x7f, 0x64, 0x24, 0x50, 0xf3, 0x0f, 0x7f,
			0x6c, 0x24, 0x60, 0xf3, 0x0f, 0x7f, 0x74, 0x24, 0x70, 0xf3, 0x0f, 0x7f,
			0xbc, 0x24, 0x80, 0x00, 0x00, 0x00, 0xc7, 0x04, 0x24, 0x9a, 0x78, 0x56,
			0x34, 0xb8, 0xab, 0x89, 0x67, 0x45, 0xff, 0xd0, 0xf3, 0x0f, 0x6f, 0x44,
			0x24, 0x10, 0xf3, 0x0f, 0x6f, 0x4c, 0x24, 0x20, 0xf3, 0x0f, 0x6f, 0x54,
			0x24, 0x30, 0xf3, 0x0f, 0x6f, 0x5c, 0x24, 0x40, 0xf3, 0x0f, 0x6f, 0x64,
			0x24, 0x50, 0xf3, 0x0f, 0x6f, 0x6c, 0x24, 0x60, 0xf3, 0x0f, 0x6f, 0x74,
			0x24, 0x70, 0xf3, 0x0f, 0x6f, 0xbc, 0x24, 0x80, 0x00, 0x00, 0x00, 0x8b,
			0x4c, 0x24, 0x08, 0x8b, 0x54, 0x24, 0x0c, 0x89, 0xec, 0x5d, 0xff, 0xe0,
		}
		out.slow = 15
		le.PutUint32(out.code[2:], uint32(cell))
		le.PutUint32(out.code[11:], uint32(cell))
		le.PutUint32(out.code[93:], uint32(context))
		le.PutUint32(out.code[98:], uint32(helper))
	default:
		return coffLazyEntry{}, fmt.Errorf("unsupported COFF lazy import architecture %s", arch)
	}
	return out, nil
}
